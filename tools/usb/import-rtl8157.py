"""Reproduce the RTL8157 tables from the pinned, unmodified Realtek GPL source.

Download src/r8152.c from awesometic/realtek-r8152-dkms at
d93c9f89ca5a831c9437e35319c546e48c710f9a, then pass its local path.
No download or code execution occurs here. The generated tables are compiled in;
the privileged receiver never loads a user-supplied firmware/register script.
"""
import hashlib
from pathlib import Path
import re
import sys

source = Path(sys.argv[1]).read_bytes()
assert hashlib.sha256(source).hexdigest() == '45b18282a0a9cc4ed007cba6bd77ac2fbb16d9015e2b4d95caee90edc0e715ce', 'wrong source revision'
text = source.decode()
out = ['// SPDX-License-Identifier: GPL-2.0-only',
       '// Copyright (c) 2024 Realtek Semiconductor Corp. All rights reserved.',
       '// Generated by tools/usb/import-rtl8157.py from Realtek r8152 v2.22.1 (2026/06/03).',
       '// Source: https://github.com/awesometic/realtek-r8152-dkms/blob/d93c9f89ca5a831c9437e35319c546e48c710f9a/src/r8152.c',
       '#pragma once', '#include <cstdint>', 'namespace rtl8157 {']
for name in ('usb_patch_16', 'pla_patch_16', 'ram16'):
    body = re.search(r'static u8 ' + name + r'\[\] = \{(.*?)\};', text, re.S)[1]
    data = bytes(int(x, 16) for x in re.findall(r'0x([0-9a-fA-F]{2})', body))
    out += [f'// {len(data)} bytes; SHA-256 {hashlib.sha256(data).hexdigest()}', f'inline constexpr uint8_t {name}[] = {{']
    out += ['    ' + ', '.join(f'0x{x:02x}' for x in data[i:i+16]) + ',' for i in range(0, len(data), 16)]
    out += ['};']
out += ['inline constexpr uint16_t phy_version = 0x0014;',
        '// P=PHY register, S=SRAM, T=second SRAM bank. Write (old & ~clear) | set.',
        '// W writes a PHY register without a read (including SRAM autoincrement).',
        'struct Setting { char bus; uint16_t address, clear, set; };',
        'inline constexpr Setting calibration[] = {']
body = text.split('static void r8157_hw_phy_cfg')[1].split('case RTL_VER_16:')[1].split('break;')[0]
body = re.sub(r'BIT\((\d+)\)', lambda m: hex(1 << int(m[1])), body)
body = body.replace('OCP_SRAM2_ADDR', '0xb87c').replace('OCP_SRAM2_DATA', '0xb87e')
body = body.replace('OCP_SRAM_ADDR', '0xa436').replace('OCP_SRAM_DATA', '0xa438')
for line in body.splitlines():
    line = line.strip()
    if not line: continue
    if line.startswith('/*'):
        out.append('    ' + line); continue
    match = re.fullmatch(r'(ocp_reg|sram2?|sram2?_write)_(write|set_bits|clr_bits|w0w1)\(tp, (.*?)\);', line)
    assert match, line
    bus, op, args = match.groups()
    values = [int(x, 16) for x in args.split(', ')]
    if op == 'write': kind, clear, value = 'W', 0, values[1]
    else:
        kind = {'ocp_reg':'P', 'sram':'S', 'sram_write':'S', 'sram2':'T', 'sram2_write':'T'}[bus]
        clear = values[1] if op != 'set_bits' else 0
        value = values[2] if op == 'w0w1' else values[1] if op == 'set_bits' else 0
    out.append(f"    {{'{kind}', 0x{values[0]:04x}, 0x{clear:04x}, 0x{value:04x}}},")
out += ['};', '} // namespace rtl8157', '']
(Path(__file__).resolve().parents[2] / 'receiver/usb/rtl8157-data.h').write_text('\n'.join(out))
